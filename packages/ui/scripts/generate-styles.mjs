import { readFile, writeFile } from "node:fs/promises";

const sourceUrl = new URL("../src/", import.meta.url);
const entryUrl = new URL("styles.css", sourceUrl);
const entry = await readFile(entryUrl, "utf8");
const imports = [...entry.matchAll(/@import\s+["'](.+?\.css)["'];?/g)].map(
  (match) => match[1],
);

if (imports.length === 0) {
  throw new Error("styles.css must contain at least one local @import");
}

const sheets = await Promise.all(
  imports.map(async (specifier) => {
    if (!specifier) {
      throw new Error("Invalid CSS import");
    }

    return readFile(new URL(specifier, sourceUrl), "utf8");
  }),
);

const css = sheets.map((sheet) => sheet.trim()).join("\n\n");
const output = `// Generated by scripts/generate-styles.mjs. Do not edit.
export const UI_CSS: string = ${JSON.stringify(css)};
`;

await writeFile(new URL("styles.generated.ts", sourceUrl), output);
